FORMATS = ['Карусель', 'Reels', 'Stories']
GOALS = ['Сохранения', 'Охват', 'Ответы аудитории']

def formats_for_platform(platform):
    """Editorial media kinds, not a claim of API publishing capability."""
    from platform_registry import canonicalize_platforms
    normalized=canonicalize_platforms(platform)
    if len(normalized)==1:
        platform=normalized[0]
    name=str(platform).casefold().strip()
    if name=='instagram': return list(FORMATS)
    # Portable content kinds for other destinations. Publishing adapters must
    # separately verify account capabilities before actual placement.
    return ['Текст с изображением', 'Видео', 'Серия изображений']


def slots_for_weeks(first, last, platform='Instagram', business=''):
    slots=[]
    for week in range(first,last+1):
        for day_idx, day in enumerate(('Пн','Ср','Пт')):
            n=(week-1)*3+day_idx
            pillar,brief=PILLARS[n % len(PILLARS)]
            angle=(n // len(PILLARS))+1
            # Each topic has a stable, distinct editorial angle; never count format as a topic.
            topic=PHARMACY_TOPICS[n] if 'аптек' in str(business).casefold() and n < len(PHARMACY_TOPICS) else f'{pillar}: {brief.lower()} (ракурс {angle})'
            slots.append({'week':week,'day':day,'platform':platform,'format':formats_for_platform(platform)[n%3],
                          'topic':topic,'brief':brief,'goal':GOALS[n%3]})
    return slots

def markdown_table(slots):
    header='| Неделя/день | Площадка и формат | Конкретная тема | Цель | Сценарий/визуал | Текст/ключевые реплики | CTA | KPI |\n|---|---|---|---|---|---|---|---|'
    rows=[]
    for s in slots:
        rows.append('| '+ ' | '.join([
            f"{s['week']}/{s['day']}", f"{s['platform']}, {s['format']}", s['topic'],
            s['goal'], s['brief']+'; показать на экране конкретные шаги и контактные данные после проверки.',
            '«Разбираем важный вопрос: '+s['topic'].split(':')[0].lower()+'. '+s['brief']+'. Уточняйте актуальные условия у сотрудников».',
            'Сохраните публикацию или задайте организационный вопрос',
            'Сохранения / охват / ответы — оценить по статистике площадки'
        ])+' |')
    return header+'\n'+'\n'.join(rows)

def validate_slots(body, slots):
    rows=count_calendar_entries(body)
    expected={(str(s['week']),s['day']) for s in slots}
    seen=set()
    for row in rows:
        if '/' in row[0]:
            w,d=row[0].split('/',1)
            seen.add((w.strip(),d.strip()))
    return len(rows)==len(slots) and seen==expected and len({r[2].casefold().strip() for r in rows})==len(rows)
