"""Recoverable deletion for a project, its originals, or its SQLite records.

The filesystem stage and the SQLite commit marker form one recoverable protocol:
without a committed marker files are restored, with it staged files are purged.
A staging directory lives beside the project so rename stays on one volume.
"""
from __future__ import annotations
import json
import re
import os
from pathlib import Path, PurePosixPath
import shutil
from uuid import uuid4

from durable_json import atomic_write_json
from project_file_boundary import reject_path_link

_STAGE_DIR = '.ai_smm_delete_staging'


def _ensure(db):
    db.execute('''CREATE TABLE IF NOT EXISTS ai_delete_commit_marks
        (op_id TEXT PRIMARY KEY, project_ref TEXT NOT NULL, scope TEXT NOT NULL,
         project_root TEXT)''')
    cols={row[1] for row in db.execute('PRAGMA table_info(ai_delete_commit_marks)')}
    if 'project_root' not in cols:
        db.execute('ALTER TABLE ai_delete_commit_marks ADD COLUMN project_root TEXT')
    db.commit()


def _safe_entry(path):
    if path.is_symlink() or getattr(path, 'is_junction', lambda: False)():
        raise ValueError('Удаление через символическую ссылку или junction запрещено')



def _valid_manifest_entry(relative, scope):
    """Allow only entries generated by the selected deletion scope.

    Full-project cleanup stages direct children of the project folder;
    asset cleanup stages files under originals/. Windows-style separators,
    absolute paths and traversal are never valid, on either platform.
    """
    if not isinstance(relative, str) or not relative or "\\" in relative or ":" in relative:
        return False
    path = PurePosixPath(relative)
    components = path.parts
    if path.is_absolute() or any(x in ('', '.', '..') for x in relative.split('/')):
        return False
    if scope == 'project':
        return len(components) == 1
    if scope == 'assets':
        return len(components) == 2 and components[0] == 'originals'
    if scope == 'documents':
        return (len(components) == 2 and
                components[0] in {'strategies', 'content_plans', 'diagrams',
                                  'reports', 'texts', 'pdf'} and
                path.suffix.lower() in {'.txt', '.pdf', '.png'})
    return False


def _document_exports(db, root, project_id, selected_ids):
    """Resolve only the chosen project's current, canonically named exports.

    No arbitrary path stored in a model response or database row may be used
    directly as a deletion target. Legacy tables without title/kind are still
    supported; they have no resolvable managed exports.
    """
    identifiers = tuple(selected_ids)
    if not identifiers or len(set(identifiers)) != len(identifiers):
        raise ValueError('Нужен непустой список уникальных документов')
    fields = {row[1] for row in db.execute('PRAGMA table_info(manager_documents)')}
    paths = []
    # Two UUIDs can share their first eight characters. Since the exported
    # names use that short suffix, never delete a file possibly owned by an
    # unselected document with the same filename stem.
    all_stems = {}
    if {'kind', 'title'} <= fields:
        for other_id, other_title in db.execute(
                'SELECT id,title FROM manager_documents WHERE project_id=?', (project_id,)):
            if isinstance(other_id, str) and isinstance(other_title, str):
                safe = re.sub(r'[<>:"/\\|?*\x00-\x1f]', '_', other_title).strip(' .')[:75] or 'document'
                key = safe + '_' + other_id[:8]
                all_stems.setdefault(key, set()).add(other_id)
    folder_by_kind = {'strategy':'strategies', 'calendar':'content_plans',
                      'plans':'diagrams', 'analytics':'reports', 'tasks':'texts'}
    for ident in identifiers:
        if not isinstance(ident, str) or not re.fullmatch(r'[a-f0-9]{32}', ident):
            raise ValueError('Недопустимый идентификатор документа')
        if {'kind','title'} <= fields:
            row = db.execute('SELECT kind,title FROM manager_documents WHERE id=? AND project_id=?',
                             (ident, project_id)).fetchone()
        else:
            row = None
            if not db.execute('SELECT 1 FROM manager_documents WHERE id=? AND project_id=?',
                              (ident, project_id)).fetchone():
                raise ValueError('Документ не найден в выбранном проекте')
        if row:
            kind, title = row
            if kind not in folder_by_kind or not isinstance(title, str):
                raise ValueError('Некорректная запись документа')
            stem = (re.sub(r'[<>:"/\\|?*\x00-\x1f]', '_', title).strip(' .')[:75]
                    or 'document') + '_' + ident[:8]
            if len(all_stems.get(stem,set())) != 1:
                raise ValueError('Имя экспорта совпадает с другим документом; удаление блокировано')
            paths.extend((root/folder_by_kind[kind]/(stem+'.txt'),
                          root/'pdf'/(stem+'.pdf'), root/'diagrams'/(stem+'.png')))
    # Durable editor revisions may have moved or renamed a document before
    # the renderer could clean old projections. Include those former names.
    has_editor_outbox = db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='manager_document_exports'").fetchone()
    if has_editor_outbox:
        from manual_document_projection import _paths
        for ident in identifiers:
            row=db.execute('''SELECT orphan_json FROM manager_document_exports
                WHERE document_id=? AND project_id=?''',(ident,project_id)).fetchone()
            if not row:continue
            old_names=json.loads(row[0])
            if not isinstance(old_names,list):raise ValueError('Повреждён журнал переименования')
            for name in old_names:
                if (not isinstance(name,list) or len(name)!=2 or
                        name[0] not in folder_by_kind or not isinstance(name[1],str)):
                    raise ValueError('Повреждена идентичность устаревшего экспорта')
                obsolete=_paths(root,ident,name[0],name[1])
                stem=obsolete[1].stem
                if any(other!=ident for other in all_stems.get(stem,set())):
                    raise ValueError('Старое имя экспорта теперь принадлежит другому документу')
                for old in obsolete:
                    if old not in paths:
                        paths.append(old)
    # A short export suffix can collide across UUIDs. Refuse ambiguous removal
    # rather than remove another document's content.
    if len(paths) != len(set(paths)):
        raise ValueError('Неоднозначные пути экспорта документов')
    return [path for path in paths if path.exists() or path.is_symlink()]


def _check_parents_no_links(path, stop):
    """Prevent symlink/junction traversal in staged and restored paths."""
    stop = Path(stop)
    cursor = Path(path)
    while cursor != stop:
        _safe_entry(cursor)
        nxt = cursor.parent
        if nxt == cursor or not cursor.is_relative_to(stop):
            raise ValueError('Путь восстановления выходит за границы каталога')
        cursor = nxt
    _safe_entry(stop)

def _restore(stage, manifest):
    original = Path(manifest['project_root'])
    content = stage / 'content'
    _check_parents_no_links(content, stage)
    for rel in reversed(manifest['entries']):
        src = content / rel
        dst = original / rel
        if not src.exists():
            continue  # Entry not yet moved when the process stopped.
        _check_parents_no_links(src, content)
        _check_parents_no_links(dst, original)
        if dst.exists() or dst.is_symlink():
            raise RuntimeError('Восстановление остановлено: исходный путь уже занят: ' + str(dst))
        dst.parent.mkdir(parents=True, exist_ok=True)
        os.replace(src, dst)
    shutil.rmtree(stage)


def recover_deletions(db, project_folders, default_root=None):
    """Reconcile interrupted deletions before the GUI can read project state."""
    if db.in_transaction:
        raise RuntimeError('Восстановление удаления требует завершённой транзакции')
    _ensure(db)
    parents = set()
    for folder in project_folders:
        root = Path(folder)
        if not root.is_absolute() or '..' in root.parts:
            raise ValueError('Invalid registered recovery location')
        reject_path_link(root)
        parents.add(root.parent)
    # A fully deleted project no longer has a location row. Its durable
    # tombstone keeps the staging parent discoverable after a crash.
    for (deleted_root,) in db.execute('''SELECT project_root FROM ai_delete_commit_marks
                                            WHERE project_root IS NOT NULL'''):
        root=Path(deleted_root)
        if not root.is_absolute():
            raise ValueError('Invalid deleted-project recovery location')
        if '..' in root.parts:
            raise ValueError('Invalid deleted-project recovery location')
        reject_path_link(root)
        parents.add(root.parent)
    if default_root is not None:
        default = Path(default_root)
        if not default.is_absolute() or '..' in default.parts:
            raise ValueError('Invalid default recovery location')
        reject_path_link(default)
        parents.add(default)
    # A write lock prevents one process from restoring a second process's
    # uncommitted staging directory. Never reconcile pending deletes unlocked.
    db.execute('BEGIN IMMEDIATE')
    try:
        _recover_locked(db, parents)
        db.commit()
    except BaseException:
        db.rollback()
        raise


def _recover_locked(db, parents):
    for parent in sorted(parents):
        base = parent / _STAGE_DIR
        if not base.is_dir():
            continue
        _safe_entry(base)
        for stage in sorted(base.iterdir()):
            _safe_entry(stage)
            if not stage.is_dir():
                raise RuntimeError('Неизвестный файл в журнале удаления: ' + str(stage))
            manifest_path = stage / 'manifest.json'
            if not manifest_path.is_file():
                # No manifest means no file was moved by the protocol.
                if not any(stage.iterdir()):
                    stage.rmdir()
                    continue
                raise RuntimeError('Повреждён журнал восстановления: ' + str(stage))
            _safe_entry(manifest_path)
            manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
            if (manifest.get('op_id') != stage.name or
                manifest.get('project_root') is None or
                manifest.get('scope') not in ('project', 'assets', 'documents', 'chat') or
                not isinstance(manifest.get('entries'), list) or
                any(not _valid_manifest_entry(v, manifest['scope'])
                    for v in manifest['entries']) or
                len(set(manifest['entries'])) != len(manifest['entries'])):
                raise RuntimeError('Повреждён контракт восстановления: ' + str(stage))
            root = Path(manifest['project_root'])
            _safe_entry(root)
            if root.parent.resolve() != parent.resolve():
                raise RuntimeError('Путь восстановления не соответствует каталогу проекта')
            committed = db.execute('SELECT 1 FROM ai_delete_commit_marks WHERE op_id=?',
                                   (stage.name,)).fetchone()
            if committed:
                shutil.rmtree(stage)
                # Remove the now-empty parent project folder only for full
                # deletions. Never remove user content written after commit.
                if manifest['scope']=='project' and root.is_dir():
                    try: root.rmdir()
                    except OSError: pass
                db.execute('DELETE FROM ai_delete_commit_marks WHERE op_id=?', (stage.name,))
            else:
                _restore(stage, manifest)
        try:
            base.rmdir()
        except OSError:
            pass


def _owned_tables(db):
    result = []
    for (name,) in db.execute("SELECT name FROM sqlite_master WHERE type='table'"):
        if name.startswith('sqlite_') or name == 'ai_delete_commit_marks':
            continue
        escaped = '"' + name.replace('"', '""') + '"'
        if 'project_id' in {row[1] for row in db.execute('PRAGMA table_info(' + escaped + ')')}:
            result.append(name)
    return result


def _reject_active_project_workers(db, project_id):
    """Fail closed before destructive mutations of an owned project.

    Startup recovery must interrupt stale attempts first; a live worker may
    otherwise commit a late response into a deleted project's output paths.
    """
    for table, predicate in (
        ('execution_attempts', "state='running'"),
        ('batch_item_receipts', "status='running'"),
        ('local_media_jobs', "state='running'"),
    ):
        if db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone():
            if db.execute('SELECT 1 FROM "'+table+'" WHERE project_id=? AND '+predicate+' LIMIT 1',
                          (project_id,)).fetchone():
                raise RuntimeError('Cannot delete a project with an active worker claim')


def delete_project_data(db, project_id, scope, project_root, selected_ids=(), *, preflight=None):
    """Execute a deletion after UI confirmation and durable backup.

    Returns True if the SQLite operation committed. Staged cleanup can finish on
    a later launch; it never counts as an uncommitted user action.
    """
    if scope not in ('project', 'assets', 'documents', 'chat'):
        raise ValueError('Недопустимая область удаления')
    if db.in_transaction:
        raise RuntimeError('Удаление запрещено внутри незавершённой SQLite-транзакции')
    _ensure(db)
    root = Path(project_root)
    if not root.is_absolute() or '..' in root.parts:
        raise ValueError('Invalid project root')
    reject_path_link(root)
    project = db.execute('SELECT 1 FROM projects WHERE id=?', (project_id,)).fetchone()
    if not project:
        raise ValueError('Проект не существует')
    location = db.execute('SELECT folder FROM project_locations WHERE project_id=?',
                          (project_id,)).fetchone()
    if location is not None and Path(location[0]) != root:
        raise ValueError('Каталог не принадлежит выбранному проекту')
    if location is None and root.name != project_id:
        raise ValueError('У проекта нет подтверждённого каталога')
    folders = [r[0] for r in db.execute('SELECT folder FROM project_locations').fetchall()]
    recover_deletions(db, folders, root.parent)
    # No arbitrary path from model output can enter this list.
    if scope == 'project' and root.exists():
        sources = [p for p in root.iterdir()]
    elif scope == 'assets' and (root / 'originals').is_dir():
        sources = [p for p in (root / 'originals').iterdir() if p.is_file()]
    elif scope == 'documents':
        sources = _document_exports(db, root, project_id, selected_ids)
    else:
        sources = []
    for source in sources:
        _check_parents_no_links(source, root)
        if source.is_dir():
            for nested in source.rglob('*'):
                _safe_entry(nested)
    entries = [p.relative_to(root).as_posix() for p in sources]
    staging_root = root.parent / _STAGE_DIR
    if staging_root.exists() or staging_root.is_symlink():
        _safe_entry(staging_root)
    stage = staging_root / uuid4().hex
    manifest = {'op_id': stage.name, 'project_ref': project_id,
                'project_root': str(root), 'scope': scope, 'entries': entries}
    committed = False
    db.execute('BEGIN IMMEDIATE')
    try:
        # Backup must observe the same locked database snapshot as deletion.
        # If it cannot be durably written, staging and deletion never begin.
        if scope=='project':
            _reject_active_project_workers(db,project_id)
        if preflight is not None:
            preflight()
        stage.mkdir(parents=True, exist_ok=False)
        atomic_write_json(stage / 'manifest.json', manifest)
        for source, rel in zip(sources, entries):
            dst = stage / 'content' / rel
            dst.parent.mkdir(parents=True, exist_ok=True)
            os.replace(source, dst)
        if scope == 'project':
            # SQLite may contain NO ACTION references among project-scoped
            # tables; defer their checks until ALL owned rows are gone.
            db.execute('PRAGMA defer_foreign_keys=ON')
            # This unscoped bridge references scoped messages and intake.
            if db.execute("SELECT 1 FROM sqlite_master WHERE name='ai_dialogue_publications'").fetchone():
                db.execute('''DELETE FROM ai_dialogue_publications
                    WHERE message_id IN (SELECT id FROM messages WHERE project_id=?)
                       OR intake_id IN (SELECT intake_id FROM ai_task_intake WHERE project_id=?)''',
                    (project_id,project_id))
            for table in _owned_tables(db):
                if table == 'project_locations':
                    continue
                quoted = '"' + table.replace('"','""') + '"'
                db.execute('DELETE FROM ' + quoted + ' WHERE project_id=?', (project_id,))
            # A project is removed from the registry, not reset to an empty
            # shell. Its registered path is part of the same transaction.
            db.execute('DELETE FROM project_locations WHERE project_id=?',(project_id,))
            if db.execute('DELETE FROM projects WHERE id=?',(project_id,)).rowcount!=1:
                raise RuntimeError('Project registry deletion was not committed')
        elif scope == 'assets':
            if db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name='media_ingest_jobs'").fetchone():
                db.execute("DELETE FROM media_ingest_jobs WHERE project_id=? AND kind='asset'",(project_id,))
            db.execute('DELETE FROM assets WHERE project_id=?', (project_id,))
        elif scope == 'documents':
            if not selected_ids:
                raise ValueError('Не выбраны документы для удаления')
            for ident in selected_ids:
                for table,id_col in (('manager_document_exports','document_id'),
                                     ('ai_file_effect_outbox','artifact_id'),
                                     ('ai_completed_artifacts','artifact_id')):
                    if db.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?",(table,)).fetchone():
                        db.execute('DELETE FROM "'+table+'" WHERE project_id=? AND '+id_col+'=?',
                                   (project_id,ident))
                if db.execute('DELETE FROM manager_documents WHERE id=? AND project_id=?',
                              (ident, project_id)).rowcount != 1:
                    raise ValueError('Документ не найден в выбранном проекте')
        else:
            db.execute('DELETE FROM messages WHERE project_id=?', (project_id,))
        db.execute('''INSERT INTO ai_delete_commit_marks
            (op_id,project_ref,scope,project_root) VALUES(?,?,?,?)''',
            (stage.name, project_id, scope, str(root)))
        db.commit()
        committed = True
    except BaseException:
        db.rollback()
        if stage.exists():
            _restore(stage, manifest)
        raise
    try:
        shutil.rmtree(stage)
        if scope=='project' and root.is_dir():
            try: root.rmdir()
            except OSError: pass
        db.execute('DELETE FROM ai_delete_commit_marks WHERE op_id=?', (stage.name,))
        db.commit()
    except OSError:
        # Committed rows and staged files are consistent. Recovery purges them.
        pass
    return True
